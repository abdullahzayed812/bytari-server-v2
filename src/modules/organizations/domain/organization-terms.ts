export interface OrganizationTermsDTO extends TermsText {
  termsKey: OrganizationTermsKey;
  /** Content hash — changes whenever the wording changes. */
  version: string;
}

function versionOf(t: TermsText): string {
  return createHash('sha256')
    .update(JSON.stringify([t.title, t.intro, ...t.clauses]))
    .digest('hex')
    .slice(0, 16);
}

export const ORGANIZATION_TERMS: Record<OrganizationTermsKey, OrganizationTermsDTO> =
  Object.fromEntries(
    ORGANIZATION_TERMS_KEYS.map((k) => [
      k,
      { termsKey: k, ...TERMS_TEXT[k], version: versionOf(TERMS_TEXT[k]) },
    ]),
  ) as Record<OrganizationTermsKey, OrganizationTermsDTO>;

/**
 * Which terms a new organization must accept: CLINIC / VETERINARY_OFFICE by
 * type; a FARM by its species (SHEEP / CATTLE, else poultry — POULTRY, MIXED
 * or a generic farm). Other organization types have no registration terms.
 */
export function termsKeyFor(
  type: string,
  farmSpecies?: string | null,
): OrganizationTermsKey | null {
  if (type === 'CLINIC') return 'CLINIC';
  if (type === 'VETERINARY_OFFICE') return 'VETERINARY_OFFICE';
  if (type === 'FARM') {
    if (farmSpecies === 'SHEEP') return 'SHEEP_FARM';
    if (farmSpecies === 'CATTLE') return 'CATTLE_FARM';
    return 'POULTRY_FARM';
  }
  return null;
}
