  /**
   * Organizations the user is an ACTIVE member of, with their org role in each.
   * FARM rows also carry `farmSpecies` (`POULTRY` | `SHEEP` | `CATTLE` | `MIXED`
   * | `null`) so the species-specific farm landings can filter without an extra
   * request per farm. Always `null` for non-FARM types. VETERINARY_OFFICE /
   * CLINIC rows also carry the derived subscription status plus
   * address/phone/logoUrl/galleryUrls (Veterinary Office Dashboard's "my
   * organizations" card — spec §3/§4, `OwnedOrganizationCard`) — always
   * `null`/`[]` for other types, sourced from the SAME batched `*_details`
   * query as the subscription dates (no extra round trip). `galleryUrls` lets
   * the card fall back to a registration photo when the owner hasn't set a
   * logo yet (registration collects gallery/license photos, never a logo).
   */
  async listMine(userId: string): Promise<
    Array<
      Organization & {
        myRole: string;
        farmSpecies: string | null;
        subscriptionStatus: FarmSubscriptionStatus | null;
        subscriptionEndDate: string | null;
        address: string | null;
        phone: string | null;
        logoUrl: string | null;
        galleryUrls: string[];
      }
    >
  > {
    const memberships = await this.memberships.listActiveOrganizationsForUser(userId);
    if (memberships.length === 0) return [];
    const roleByOrg = new Map(memberships.map((m) => [m.organizationId, m.roleKey]));
    const orgs = await this.organizations.findManyByIds([...roleByOrg.keys()]);

    const farmIds = orgs.filter((o) => o.type === 'FARM').map((o) => o.id);
    const speciesByOrg = new Map<string, string | null>();
    if (farmIds.length > 0) {
      const rows = (await this.db('farm_details')
        .whereIn('organization_id', farmIds)
        .select('organization_id', 'farm_species')) as Array<{
        organization_id: string;
        farm_species: string | null;
      }>;
      for (const r of rows) speciesByOrg.set(r.organization_id, r.farm_species);
    }

    const subscriptionByOrg = new Map<
      string,
      { status: FarmSubscriptionStatus; endDate: string | null }
    >();
    const profileByOrg = new Map<
      string,
      { address: string | null; phone: string | null; logoKey: string | null; galleryKeys: string[] }
    >();
    const officeIds = orgs.filter((o) => o.type === 'VETERINARY_OFFICE').map((o) => o.id);
    const clinicIds = orgs.filter((o) => o.type === 'CLINIC').map((o) => o.id);
    for (const [table, ids] of [
      ['veterinary_office_details', officeIds],
      ['clinic_details', clinicIds],
    ] as const) {
      if (ids.length === 0) continue;
      const rows = (await this.db(table)
        .whereIn('organization_id', ids)
        .select(
          'organization_id',
          'subscription_start_date',
          'subscription_end_date',
          'address',
          'phone',
          'logo_key',
          'gallery_keys',
        )) as Array<{
        organization_id: string;
        subscription_start_date: string | Date | null;
        subscription_end_date: string | Date | null;
        address: string | null;
        phone: string | null;
        logo_key: string | null;
        gallery_keys: string[] | null;
      }>;
      for (const r of rows) {
        const startDate = toDateOnlyString(r.subscription_start_date);
        const endDate = toDateOnlyString(r.subscription_end_date);
        subscriptionByOrg.set(r.organization_id, {
          status: computeFarmSubscriptionStatus(startDate, endDate),
          endDate,
        });
        profileByOrg.set(r.organization_id, {
          address: r.address,
          phone: r.phone,
          logoKey: r.logo_key,
          galleryKeys: r.gallery_keys ?? [],
        });
      }
    }
    const logoUrlByKey = new Map<string, string | null>();
    const allKeys = new Set<string>();
    for (const p of profileByOrg.values()) {
      if (p.logoKey) allKeys.add(p.logoKey);
      for (const key of p.galleryKeys) allKeys.add(key);
    }
    await Promise.all(
      [...allKeys].map(async (key) => {
        if (!logoUrlByKey.has(key)) logoUrlByKey.set(key, await this.resolveLogoUrl(key));
      }),
    );

    return orgs.map((o) => {
      const profile = profileByOrg.get(o.id);
      return {
        ...o,
        myRole: roleByOrg.get(o.id) ?? 'STAFF',
        farmSpecies: o.type === 'FARM' ? (speciesByOrg.get(o.id) ?? null) : null,
        subscriptionStatus: subscriptionByOrg.get(o.id)?.status ?? null,
        subscriptionEndDate: subscriptionByOrg.get(o.id)?.endDate ?? null,
        address: profile?.address ?? null,
        phone: profile?.phone ?? null,
        logoUrl: profile?.logoKey ? (logoUrlByKey.get(profile.logoKey) ?? null) : null,
        galleryUrls: (profile?.galleryKeys ?? [])
          .map((key) => logoUrlByKey.get(key))
          .filter((url): url is string => url != null),
      };
    });
  }

  async approve(id: string, actor: OrgActor): Promise<Organization> {
    const org = await this.getById(id);
    if (org.status !== 'PENDING') {
      throw new ConflictError('Only a pending organization can be approved');
    }
    const updated = await this.db.transaction(async (tx) => {
      const u = await this.organizations.updateStatus(
        id,
        { status: 'ACTIVE', decidedBy: actor.actorUserId, decisionReason: null },
        tx,
      );
      await this.audit.record(
        {
          action: AuditAction.ORGANIZATION_APPROVED,
          entityType: AuditEntityType.ORGANIZATION,
          entityId: id,
          actorUserId: actor.actorUserId,
          metadata: { type: org.type },
          context: actor.context,
        },
        tx,
      );
      return u;
    });
    this.events.publish('organization.approved', {
      organizationId: id,
      ownerUserId: org.ownerUserId,
    });
    return updated;
  }

  async reject(id: string, reason: string, actor: OrgActor): Promise<Organization> {
    const org = await this.getById(id);
    if (org.status !== 'PENDING') {
      throw new ConflictError('Only a pending organization can be rejected');
    }
    const updated = await this.db.transaction(async (tx) => {
      const u = await this.organizations.updateStatus(
        id,
        { status: 'REJECTED', decidedBy: actor.actorUserId, decisionReason: reason },
        tx,
      );
      await this.audit.record(
        {
          action: AuditAction.ORGANIZATION_REJECTED,
          entityType: AuditEntityType.ORGANIZATION,
          entityId: id,
          actorUserId: actor.actorUserId,
          metadata: { type: org.type, reason },
          context: actor.context,
        },
        tx,
      );
      return u;
    });
    this.events.publish('organization.rejected', {
      organizationId: id,
      ownerUserId: org.ownerUserId,
    });
    return updated;
  }

  async changeStatus(
    id: string,
    op: 'suspend' | 'activate' | 'deactivate',
    actor: OrgActor,
    reason?: string,
  ): Promise<Organization> {
    const org = await this.getById(id);
    if (org.status === 'PENDING' || org.status === 'REJECTED') {
      throw new ConflictError(
        'Use approve/reject for a pending organization; status changes apply to reviewed organizations only',
      );
    }
    const rule = NON_ADMIN_STATUS_CHANGE[op];
    if (!rule.from.includes(org.status)) {
      throw new ConflictError(`Cannot ${op} an organization in status ${org.status}`);
    }

    const updated = await this.db.transaction(async (tx) => {
      const u = await this.organizations.updateStatus(id, { status: rule.to }, tx);
      await this.audit.record(
        {
          action: rule.action,
          entityType: AuditEntityType.ORGANIZATION,
          entityId: id,
          actorUserId: actor.actorUserId,
          metadata: { from: org.status, to: rule.to, reason: reason ?? null },
          context: actor.context,
        },
        tx,
      );
      return u;
    });
    this.events.publish(rule.event, { organizationId: id, ownerUserId: org.ownerUserId });
    return updated;
  }
