function toDateOnlyString(v: string | Date | null): string | null {
  if (v === null) return null;
  return v instanceof Date ? v.toISOString().slice(0, 10) : v.slice(0, 10);
}

/** Shared by the logo AND the gallery — both are plain organization photos. */
const ALLOWED_IMAGE_MIME = ['image/png', 'image/jpeg', 'image/webp'] as const;
/** Hard ceiling per image (5 MiB — mirrors the user avatar limit). */
const MAX_IMAGE_BYTES = 5 * 1024 * 1024;
const IMAGE_UPLOAD_URL_TTL_SECONDS = 600;
const IMAGE_URL_TTL_SECONDS = 3600;
/** Directory profile photos beyond the logo — the Clinic Details carousel. */
const MAX_GALLERY_IMAGES = 8;
/** License/registration document photos — "صور الترخيص" on the registration form. */
const MAX_LICENSE_DOCUMENTS = 3;
/** CLINIC / VETERINARY_OFFICE only — narrower than `hasProfileFields` (excludes VETERINARY_STORE). */
const LICENSABLE_TYPES: ReadonlySet<OrganizationType> = new Set(['CLINIC', 'VETERINARY_OFFICE']);

export interface OrgActor {
  actorUserId: string;
  context?: AuditContext;
}

/**
 * Type-specific detail columns written into the subtype `*_details` row in the
 * SAME transaction as the organization + owner membership. Keys are the exact
 * DB column names of that detail table (e.g. `farm_details`); a domain-specific
 * creation use case (the "Add Poultry Farm" form) builds this map. Unknown
 * columns are a DB error, never a silent drop. `join_code` for FARM is still
 * generated by the service and merged on top.
 */
export type CreateOrganizationDetails = Record<string, string | number | boolean | string[] | null>;

/**
 * Typed, camelCase profile fields for `hasProfileFields` types (CLINIC /
 * VETERINARY_OFFICE / VETERINARY_STORE) — separate from the raw-snake-case
 * `details` escape hatch above (used by FARM/livestock creation, whose fields
 * live on a differently-shaped table). The "تسجيل العيادة" / office
 * registration screens capture the full profile in one submission instead of
 * create-then-PATCH, because the owner cannot call `PATCH` (or the
 * gallery/license-document endpoints without `allowInactiveForOwner`) until
 * an admin approves the PENDING organization.
 */
export interface CreateOrganizationProfileInput {
  address?: string | null;
  country?: string | null;
  phone?: string | null;
  workingHours?: string | null;
  services?: string[];
  email?: string | null;
  whatsapp?: string | null;
  websiteUrl?: string | null;
  instagramUrl?: string | null;
  facebookUrl?: string | null;
  tiktokUrl?: string | null;
  /** CLINIC / VETERINARY_OFFICE only. */
  licenseNumber?: string | null;
}

export interface CreateOrganizationInput {
  type: OrganizationType;
  name: string;
  description?: string | null;
  /** Raw snake-case detail columns — FARM/livestock creation. */
  details?: CreateOrganizationDetails;
  /** Typed camelCase profile fields — CLINIC / VETERINARY_OFFICE / VETERINARY_STORE registration. */
  profile?: CreateOrganizationProfileInput;
}

